

from pathlib import Path
import shutil
import subprocess
import sys

# ============================================================
# CONFIGURATION
# ============================================================

VAULT = Path(r"C:\Users\pelaf\Documents\Obsidian-vault")
REPO = Path(__file__).resolve().parent
CONTENT = REPO / "content"

WELCOME_NOTE = "Home.md"
WELCOME_TITLE = "Home"

BRANCH = "main"
REMOTE = "origin"

EXCLUDED_DIRS = {
    ".obsidian",
    ".trash",
    "templates",
    "private",
    ".git",
}

EXCLUDED_FILES = {
    ".DS_Store",
}


# ============================================================
# GIT UTILITIES
# ============================================================

def run(command, cwd=REPO):
    print(f"\n> {' '.join(map(str, command))}")
    subprocess.run(command, cwd=cwd, check=True, shell=False)


def git_output(command):
    result = subprocess.run(
        command,
        cwd=REPO,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def commit_pending_changes(message):
    """Automatically commit all pending repository changes."""

    print("\nSaving pending repository changes...")

    run(["git", "add", "-A"])

    result = subprocess.run(
        ["git", "diff", "--cached", "--quiet"],
        cwd=REPO,
    )

    if result.returncode == 0:
        print("No pending changes.")
        return

    if result.returncode != 1:
        raise RuntimeError("Could not check pending Git changes.")

    run(["git", "commit", "-m", message])


def pull_latest():
    """Retrieve remote changes without overwriting local work."""

    print("\nSynchronizing with GitHub...")

    run([
        "git",
        "pull",
        "--rebase",
        REMOTE,
        BRANCH,
    ])


def publish_git():
    """Commit and push all changes generated by the update."""

    print("\nPublishing website changes...")

    commit_pending_changes("Update Obsidian website")

    run([
        "git",
        "push",
        REMOTE,
        BRANCH,
    ])


# ============================================================
# VAULT SYNCHRONIZATION
# ============================================================

def is_excluded(relative_path):
    return any(
        part in EXCLUDED_DIRS
        for part in relative_path.parts
    )


def copy_vault():
    """Copy public notes and images from Obsidian to Quartz."""

    print("\nSynchronizing Obsidian notes and images...")

    CONTENT.mkdir(parents=True, exist_ok=True)

    # Remove files that no longer exist in the source vault.
    for path in sorted(
        CONTENT.rglob("*"),
        key=lambda p: len(p.parts),
        reverse=True,
    ):
        relative = path.relative_to(CONTENT)

        if is_excluded(relative):
            continue

        source = VAULT / relative

        if path.is_file() and not source.is_file():
            path.unlink()
            print(f"  Deleted: {relative}")

        elif path.is_dir() and not source.is_dir():
            shutil.rmtree(path)
            print(f"  Deleted folder: {relative}")

    # Copy current vault files.
    for source in VAULT.rglob("*"):

        relative = source.relative_to(VAULT)

        if is_excluded(relative):
            continue

        if not source.is_file():
            continue

        if source.name in EXCLUDED_FILES:
            continue

        # Homepage is generated separately.
        if source.name == WELCOME_NOTE:
            continue

        destination = CONTENT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)

        if (
            not destination.exists()
            or source.stat().st_mtime_ns != destination.stat().st_mtime_ns
            or source.stat().st_size != destination.stat().st_size
        ):
            shutil.copy2(source, destination)
            print(f"  Updated: {relative}")


# ============================================================
# HOMEPAGE GENERATION
# ============================================================

def generate_homepage():

    print("\nGenerating homepage...")

    source = VAULT / WELCOME_NOTE

    if not source.exists():
        raise FileNotFoundError(
            f"Homepage note not found: {source}"
        )

    body = source.read_text(encoding="utf-8-sig")

    # Remove existing frontmatter if present.
    if body.startswith("---"):
        parts = body.split("---", 2)

        if len(parts) == 3:
            body = parts[2].lstrip("\r\n")

    # Avoid duplicate H1.
    lines = body.splitlines()

    if lines and lines[0].strip() == f"# {WELCOME_TITLE}":
        lines = lines[1:]

    body = "\n".join(lines).strip()

    homepage = (
        "---\n"
        f'title: "{WELCOME_TITLE}"\n'
        "---\n\n"
        f"{body}\n"
    )

    (CONTENT / "index.md").write_text(
        homepage,
        encoding="utf-8",
    )


# ============================================================
# QUARTZ BUILD
# ============================================================

def build_website():

    print("\nBuilding Quartz website...")

    run([
        "npx.cmd",
        "quartz",
        "build",
    ])


# ============================================================
# MAIN WORKFLOW
# ============================================================

def main():

    print("\n===================================")
    print("       OBSIDIAN WEBSITE UPDATE")
    print("===================================")

    # Check project structure.
    if not VAULT.is_dir():
        raise FileNotFoundError(
            f"Obsidian vault not found: {VAULT}"
        )

    if not (REPO / ".git").is_dir():
        raise FileNotFoundError(
            "Git repository not found."
        )

    if not (REPO / "package.json").is_file():
        raise FileNotFoundError(
            "Quartz package.json not found."
        )

    if not (REPO / "node_modules").is_dir():
        raise FileNotFoundError(
            "node_modules not found. Run npm install first."
        )

    # Verify branch.
    branch = git_output([
        "git",
        "branch",
        "--show-current",
    ])

    if branch != BRANCH:
        raise RuntimeError(
            f"You are on branch '{branch}', not '{BRANCH}'. "
            f"Switch to {BRANCH} before publishing."
        )

    # 1. Save any existing local changes.
    commit_pending_changes(
        "Save pending website changes"
    )

    # 2. Retrieve remote changes.
    pull_latest()

    # 3. Synchronize Obsidian notes and images.
    copy_vault()

    # 4. Generate homepage.
    generate_homepage()

    # 5. Build website.
    build_website()

    # 6. Commit and publish everything.
    publish_git()

    print("\n===================================")
    print("              DONE!")
    print("===================================")

    print("\nGitHub Pages deployment has been triggered.")
    print(
        "https://pelayo-felgueroso.github.io/githubpage/"
    )


if __name__ == "__main__":

    try:
        main()

    except subprocess.CalledProcessError as error:
        print(
            f"\nERROR: Command failed with exit code "
            f"{error.returncode}"
        )
        sys.exit(1)

    except Exception as error:
        print(f"\nERROR: {error}")
        sys.exit(1)
